// Normalize a proof.json into the UI fields and the payload passed to contract
function normalizeProof(obj) {
  const p = obj && typeof obj === 'object' ? obj : {};
  const pi = p.public_inputs || p.publicInputs || {};
  const wallet = pi.proofpass_wallet_raw || pi.investor_wallet || pi.investorWallet || ('0x' + randHex(64));
  const proof = {
    system: 'SP1 Groth16',
    curve: 'BN254',
    pi_a: p.pi_a || null,
    pi_b: p.pi_b || null,
    pi_c: p.pi_c || null,
    investorWallet: wallet,
    nullifier: pi.nullifier || ('0x' + randHex(64)),
    timestamp: pi.timestamp || 1794333989,
    raw: p,
  };
  proof.valid = !!(proof.pi_a && proof.pi_b && proof.pi_c);
  return proof;
}

