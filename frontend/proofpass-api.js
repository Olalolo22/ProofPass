export const proof = {
  async parse(input) {
    let obj;
    if (input && typeof input.text === 'function' && input.name) {
      obj = JSON.parse(await readFileText(input));
    } else if (typeof input === 'string') {
      obj = JSON.parse(input);
    } else {
      obj = input || {};
    }
    return normalizeProof(obj);
  },
};

