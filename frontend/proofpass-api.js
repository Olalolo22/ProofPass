// 3) VERIFIER — submit to ZkInvestorGate.verify_and_authorize on Soroban
// ============================================================================
export const verifier = {
  async submit({ address, proof: p }, onStatus = () => {}) {
    if (config.USE_MOCK) {
      onStatus('pending');
      await delay(config.mockTiming.pending);
      onStatus('verifying');
      await delay(config.mockTiming.verifying);
      const txHash = randHex(64);
      onStatus('verified');
      return { txHash, status: 'verified', explorerUrl: config.explorerBase + '/tx/' + txHash };
    }

    const StellarSdk = await getStellarSdk();
    const fa = await getFreighterApi();
    if (!fa) {
      throw new Error('Freighter wallet extension not found to sign transaction.');
    }

    const server = new StellarSdk.rpc.Server(config.rpcUrl);
    const account = await server.getAccount(address);
    const contract = new StellarSdk.Contract(config.contractId);

    const raw = p.raw || p;
    const pi = raw.public_inputs || raw.publicInputs || {};

    // 1. Encode Groth16Proof { a: Bn254G1Affine, b: Bn254G2Affine, c: Bn254G1Affine }
    const proofScVal = StellarSdk.nativeToScVal({
      a: hexToBytes(raw.pi_a),
      b: hexToBytes(raw.pi_b),
      c: hexToBytes(raw.pi_c),
    });

    // 2. Encode PublicInputs { investor_wallet: BytesN<32>, nullifier: BytesN<32>, timestamp: u64 }
    const walletHex = pi.proofpass_wallet_raw || pi.investor_wallet || pi.investorWallet || raw.investorWallet;
    const nullifierHex = pi.nullifier || raw.nullifier;
    const ts = BigInt(pi.timestamp || raw.timestamp || 1794333989);

    const publicInputsScVal = StellarSdk.nativeToScVal({
      investor_wallet: hexToBytes(walletHex),
      nullifier: hexToBytes(nullifierHex),
      timestamp: ts,
    });

    // 3. Addresses
    const investorScVal = new StellarSdk.Address(address).toScVal();
    const rwaScVal = new StellarSdk.Address(config.rwaAssetContract).toScVal();

    // 4. Build invocation transaction
    let tx = new StellarSdk.TransactionBuilder(account, {
      fee: '1000000',
      networkPassphrase: config.networkPassphrase,
    })
      .addOperation(
        contract.call('verify_and_authorize', proofScVal, publicInputsScVal, investorScVal, rwaScVal)
      )
      .setTimeout(120)
      .build();

    onStatus('pending');

    // 5. Simulate & assemble footprint + resource fees via Soroban RPC
    tx = await server.prepareTransaction(tx);

    // 6. Sign with Freighter wallet
    let signedResult;
    if (typeof fa.signTransaction === 'function') {
      signedResult = await fa.signTransaction(tx.toXDR(), {
        networkPassphrase: config.networkPassphrase,
      });
    } else {
      throw new Error('Freighter signTransaction method is unavailable.');
    }

    const signedTxXdr = typeof signedResult === 'string'
      ? signedResult
      : (signedResult && (signedResult.signedTxXdr || signedResult.xdr));
    if (!signedTxXdr) {
      throw new Error('Transaction signing was cancelled by user.');
    }

    const signedTx = StellarSdk.TransactionBuilder.fromXDR(signedTxXdr, config.networkPassphrase);

    onStatus('verifying');

    // 7. Send to network
    const sent = await server.sendTransaction(signedTx);
    if (sent.status === 'ERROR') {
      const errDetail = sent.errorResultXdr || JSON.stringify(sent);
      throw new Error('Submission error from Soroban RPC: ' + errDetail);
    }

    // 8. Poll for transaction confirmation
    let txRes = await server.getTransaction(sent.hash);
    let attempts = 0;
    while (txRes.status === 'NOT_FOUND' && attempts < 35) {
      await delay(1200);
      txRes = await server.getTransaction(sent.hash);
      attempts++;
    }

    if (txRes.status !== 'SUCCESS') {
      throw new Error('On-chain verification failed: ' + txRes.status + ' (' + (txRes.resultXdr || '') + ')');
    }

    onStatus('verified');
    return {
      txHash: sent.hash,
      status: 'verified',
      explorerUrl: config.explorerBase + '/tx/' + sent.hash,
    };
  },

  // Read-only check against ZkInvestorGate.is_authorized(wallet)
  async isAuthorized(walletBytes32) {
    if (config.USE_MOCK) {
      await delay(200);
      return false;
    }
    const StellarSdk = await getStellarSdk();
    const server = new StellarSdk.rpc.Server(config.rpcUrl);
    const contract = new StellarSdk.Contract(config.contractId);
    const dummyAcc = new StellarSdk.Account('GBF6KUW5D7B5BGODLDSZ4OMR45MWWZCPNEKQBDUNJE5TKJAMYVNYJD3G', '1');
    const bytes = hexToBytes(walletBytes32);

    const tx = new StellarSdk.TransactionBuilder(dummyAcc, {
      fee: '100',
      networkPassphrase: config.networkPassphrase,
    })
      .addOperation(contract.call('is_authorized', StellarSdk.nativeToScVal(bytes)))
      .setTimeout(30)
      .build();

    const sim = await server.simulateTransaction(tx);
    if (StellarSdk.rpc.Api.isSimulationSuccess(sim)) {
      return StellarSdk.scValToNative(sim.result.retval);
    }
    return false;
  },
};

